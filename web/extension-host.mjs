// In-browser extension host, runtime-guest lane.
//
// Boots each DuckDB extension component through the SAME wasm-cm runtime-guest
// driver that ran the core (`run-core.mjs::createDuckLinkDriver`), provides
// the extension's `duckdb:extension/runtime|catalog|files` imports as JS
// closures (registrations flow into a per-extension `pending` record), and
// exposes the CORE-side imports the core component needs
// (`host-extension-loader`, `extension-loader-hooks`, `callback-dispatch`) via
// {@link createExtensionHost#coreImports}. Callback dispatch forwards to each
// loaded extension's own `callback-dispatch` export through the same driver's
// `callExport`.
//
// # Per-extension bindings
//
// Each extension component has its own WIT surface (runtime/catalog/files
// interface versions, guest.load / callback-dispatch exports), so each needs
// its own generated bindings pair — regenerated by `web/generate.sh` alongside
// the core bindings. The bindings live at
// `web/bindings-runtime-guest/<name>.runtime-guest.mjs` and expose the same
// `registerHostProviders` + `bindRuntimeGuest` shape the core bindings do.
//
// # Instantiation is async, dispatch is sync (from the guest's POV)
//
// Component instantiation goes through the driver's JSPI-async
// `instantiateWithImports`, so `preload()` is async. Once loaded, the core
// calls `request-load` synchronously; the cached result is returned. Callback
// dispatch back into the extension is byte-frame in / byte-frame out through
// the driver, wrapped as async by the generated bindings (JSPI-safe).

import { createWasiProviders } from '@wasmos/runtime-guest-bridge'

// -----------------------------------------------------------------------------
// The wasi interface set an extension component may import. Extensions built
// against different wasi tags (cron / cron_scheduler are @0.2.3, aba is
// @0.2.9) resolve through the polyfill's version-agnostic matcher, but the
// bindings' `registerHostProviders` looks up impls by the EXACT interface
// string the wasm imports — so both tag sets are requested up front and the
// bindings pick whatever the extension binary actually declares. Missing
// interfaces are silently dropped by `createWasiProviders`.
// -----------------------------------------------------------------------------
